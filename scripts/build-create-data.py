def load(name):
    p = SRC / name
    if not p.exists():
        sys.exit(f'덤프 없음: {p}')
    return json.loads(p.read_text(encoding='utf-8'))


def cat_tree(nodes, missing):
    out = []
    for c in nodes or []:
        zh = c['categoryName']
        ko = CAT_KO.get(zh)
        if ko is None:
            missing.add(zh)
            ko = zh
        node = {'id': c['categoryId'], 'name': ko, 'zh': zh}
        kids = cat_tree(c.get('children'), missing)
        if kids:
            node['children'] = kids
        out.append(node)
    return out


def material_name(zh, missing):
    s = zh.strip().replace('（', '(').replace('）', ')')
    if s in MAT_KO:
        return MAT_KO[s]
    m = re.match(r'^(.*?)\((.+?)\)?$', s) if '(' in s else None
    if m and m.group(1) in MAT_KO and m.group(2).rstrip(')') in MAT_SUFFIX_KO:
        return f'{MAT_KO[m.group(1)]}({MAT_SUFFIX_KO[m.group(2).rstrip(")")]})'
    missing.add(zh)
    return zh


def main():
    prodcats = {x['position']: x['categories'] for x in load('editor-prodcats.json')['cabinet']}
    lines = {b['id']: b for b in load('api-1.json')['dynCfg']['d']['businessLineConfigs']}
    missing = set()

    model_types = {}
    for tool, cfg in TOOLTYPES.items():
        libs = {x['library']: x for x in lines[cfg['line']]['libraries']}
        out = []
        for group in ('front', 'back'):
            for lib in cfg[group]:
                d = libs[lib]
                out.append({
                    'lib': lib, 'name': LIB_KO[d['name']], 'zh': d['name'], 'group': group, 'position': d['position'],
                    'cats': cat_tree(prodcats.get(d['position']), missing),
                })
        model_types[tool] = {'libs': out}

    mats = load('material-api.json')['/mmus/api/physicaltexture/r?version=4&pos=1&uploadtype=3']['d']
    groups = []
    for m in mats:
        if not m.get('visible', True):
            continue
        base = m['baseCategory']
        g = next((x for x in groups if x['zh'] == base), None)
        if g is None:
            g = {'name': MAT_BASE_KO.get(base, base), 'zh': base, 'items': []}
            groups.append(g)
        # img = 장면 렌더(재질 공) — 쿠지알러 재질 단계식 고르기의 26px 아이콘 원본
        g['items'].append({'id': m['obsPtextureId'], 'name': material_name(m['name'], missing), 'zh': m['name'].strip(), 'img': m.get('sceneImage', '')})

    if missing:
        sys.exit('번역 없음: ' + '、'.join(sorted(missing)))
    OUT_MODEL.write_text(json.dumps(model_types, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    OUT_MATERIAL.write_text(json.dumps(groups, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    n_cat = sum(1 for _ in re.finditer('"id":', OUT_MODEL.read_text(encoding='utf-8')))
    print(f'{OUT_MODEL.name} — 도구 {len(model_types)}종, 분류 노드 {n_cat}개 ({OUT_MODEL.stat().st_size / 1024:.0f} KB)')
    print(f'{OUT_MATERIAL.name} — 대분류 {len(groups)}개, 재질 {sum(len(g["items"]) for g in groups)}개 ({OUT_MATERIAL.stat().st_size / 1024:.0f} KB)')


if __name__ == '__main__':
    main()
